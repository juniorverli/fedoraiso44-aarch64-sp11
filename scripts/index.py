#!/usr/bin/env python3
"""Generate hardware/INDEX.md from hardware/*/component.toml.

  python3 scripts/index.py          write hardware/INDEX.md
  python3 scripts/index.py --check  validate only; exit 1 on any error

Checks: required keys, known status, phase is an int, dependencies exist,
and every Windows package name matches a folder in sources/windows/DriverStore
(names marked "(inbox)" or containing "*" are matched loosely or skipped).
"""
import glob
import os
import sys
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HW = os.path.join(ROOT, "hardware")
STORE = os.path.join(ROOT, "sources", "windows", "DriverStore")
STATUSES = ["survey", "designed", "sw-ready", "testing", "pass", "blocked", "absent"]
REQUIRED = ["id", "name", "phase", "status", "depends_on", "updated"]


def load():
    comps = {}
    for path in sorted(glob.glob(os.path.join(HW, "*", "component.toml"))):
        with open(path, "rb") as f:
            comps[os.path.basename(os.path.dirname(path))] = tomllib.load(f)
    return comps


def store_packages():
    if not os.path.isdir(STORE):
        return None
    return {d.split(".inf_arm64_")[0].lower() for d in os.listdir(STORE)
            if os.path.isdir(os.path.join(STORE, d))}


def check(comps):
    errors = []
    pkgs = store_packages()
    for folder, c in comps.items():
        for k in REQUIRED:
            if k not in c:
                errors.append(f"{folder}: missing key {k}")
        if c.get("id") != folder:
            errors.append(f"{folder}: id {c.get('id')!r} differs from folder")
        if c.get("status") not in STATUSES:
            errors.append(f"{folder}: unknown status {c.get('status')!r}")
        if not isinstance(c.get("phase"), int):
            errors.append(f"{folder}: phase must be an integer")
        for dep in c.get("depends_on", []):
            if dep not in comps:
                errors.append(f"{folder}: unknown dependency {dep}")
        if pkgs is None:
            continue
        for p in c.get("windows", {}).get("packages", []):
            name = p.split(" ")[0].lower()
            if "(inbox)" in p:
                continue
            if "*" in name:
                prefix = name.split("*")[0]
                if not any(x.startswith(prefix) for x in pkgs):
                    errors.append(f"{folder}: no DriverStore package matches {p}")
            elif name not in pkgs:
                errors.append(f"{folder}: DriverStore has no package {p}")
    return errors


def render(comps):
    rows = sorted(comps.values(), key=lambda c: (c["phase"], c["id"]))
    out = [
        "# Hardware index",
        "",
        "Generated by `scripts/index.py` from `hardware/*/component.toml`. Do not edit by hand.",
        "",
        "`native` is what Linux 7.3 provides by static reading of the source, not tested on the device.",
        "",
        "| Phase | Component | Status | 7.3 native | Main gaps | Dossier |",
        "|:--:|:--|:--|:--|:--|:--|",
    ]
    for c in rows:
        phase = "later" if c["phase"] >= 99 else str(c["phase"])
        gaps = c.get("linux", {}).get("gaps", [])
        gap = "; ".join(gaps[:2]) + (f" (+{len(gaps) - 2})" if len(gaps) > 2 else "")
        native = c.get("linux", {}).get("native", "?")
        out.append(f"| {phase} | {c['name']} | `{c['status']}` | {native} | {gap or '—'} | "
                   f"[`{c['id']}`]({c['id']}/README.md) |")
    out += ["", "## Firmware needed", "", "| Component | File |", "|:--|:--|"]
    for c in rows:
        for need in c.get("firmware", {}).get("needs", []):
            out.append(f"| `{c['id']}` | {need} |")
    out.append("")
    return "\n".join(out)


def main():
    comps = load()
    errors = check(comps)
    for e in errors:
        print("ERROR", e, file=sys.stderr)
    if "--check" in sys.argv:
        print(f"{len(comps)} components, {len(errors)} errors")
        return 1 if errors else 0
    with open(os.path.join(HW, "INDEX.md"), "w") as f:
        f.write(render(comps))
    print(f"wrote hardware/INDEX.md ({len(comps)} components, {len(errors)} errors)")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
